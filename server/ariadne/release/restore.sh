#!/usr/bin/env bash
# Restore of an Ariadne release (STRUCTURE.md, section 16).
#
#   ./restore.sh -k PUBLIC_KEY.pub | --pubkey 'ssh-ed25519 AAAA…'   (required)
#                [-i AGE_PRIVATE_KEY_FILE] [-d PARTS_FOLDER] [-o OUTPUT_FOLDER]
#                [--expect-manifest-sha256 HEX] [--database NAME]
#
# The SIGNING public key (RELEASE_SIGNING_PUBKEY, the one you pinned outside GitHub) is given as
# an argument, a file or the RELEASE_SIGNING_PUBKEY environment variable: it is never read from
# the archive.
# Steps, in order:
# 1. verifies the signature of MANIFEST.json (and refuses if it does not match: authenticity);
# 2. validates the fingerprints of the parts against that signed manifest;
# 3. asks for the age private key (the file; it was never on the system that built the release),
#    decrypts, checks the content sha-256, refuses dangerous paths and restores into
#    OUTPUT_FOLDER/ariadne-release/;
# 4. with --database NAME (the target database, connecting through the PGHOST/PGUSER/PGPASSWORD
#    variables or ~/.pgpass: the password never goes on the command line) creates the
#    ariadne_release schema and loads db/*.csv with COPY FROM STDIN. The archive's SQL is NEVER
#    run: the schema comes from this script and the archive only carries data. Preferably use a
#    separate database and an unprivileged role.
#
# This script ships with the release only for convenience: the signed manifest carries its
# sha-256 (restore_sh_sha256) and `ariadne release verify` checks it; when in doubt use the one
# in the repository (server/ariadne/release/restore.sh, once generated by Ariadne) or the one
# from a previous release. The plaintext only exists in a temporary folder that is deleted at
# the end. Needs: ssh-keygen, age, tar and sha256sum (or shasum); psql only with --database.
set -euo pipefail

say() { printf '%s\n' "$*" >&2; }
die() { say "restore.sh: $*"; exit "${2:-1}"; }

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IDENTITY="${ARIADNE_AGE_IDENTITY:-}"
PUBKEY="${RELEASE_SIGNING_PUBKEY:-}"
OUT="./ariadne-restore"
DATABASE=""
EXPECT=""

while [ $# -gt 0 ]; do
  case "$1" in
    -d) DIR="$(cd "$2" && pwd)"; shift 2 ;;
    -i) IDENTITY="$2"; shift 2 ;;
    -k) [ -r "$2" ] || die "cannot read the public key at $2" 64; PUBKEY="$(head -n 1 "$2")"; shift 2 ;;
    --pubkey) PUBKEY="$2"; shift 2 ;;
    -o) OUT="$2"; shift 2 ;;
    --database) DATABASE="$2"; shift 2 ;;
    --expect-manifest-sha256) EXPECT="$2"; shift 2 ;;
    -h|--help) sed -n '2,29p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1" 64 ;;
  esac
done

for tool in ssh-keygen age tar; do command -v "$tool" >/dev/null || die "$tool is missing"; done
if command -v sha256sum >/dev/null; then SUM=(sha256sum); else SUM=(shasum -a 256); fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/ariadne-restore.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
chmod 700 "$TMP"

[ -f "$DIR/MANIFEST.json" ] || die "cannot find $DIR/MANIFEST.json"
[ -f "$DIR/MANIFEST.json.sig" ] || die "cannot find the signature $DIR/MANIFEST.json.sig: refusing an unsigned release" 2

# 1. the signature, before anything else
[ -n "$PUBKEY" ] || die "the signing public key is missing (-k FILE, --pubkey 'ssh-ed25519 AAAA…' or RELEASE_SIGNING_PUBKEY)" 64
set -- $PUBKEY
[ "${1:-}" = "ssh-ed25519" ] && [[ "${2:-}" =~ ^[A-Za-z0-9+/]{40,}=*$ ]] || die "the signing public key must be \"ssh-ed25519 AAAA…\"" 64
printf 'ariadne-release namespaces="ariadne-release" %s %s\n' "$1" "$2" > "$TMP/allowed_signers"
say "1/4 verifying the manifest signature…"
ssh-keygen -Y verify -f "$TMP/allowed_signers" -I ariadne-release -n ariadne-release \
  -s "$DIR/MANIFEST.json.sig" < "$DIR/MANIFEST.json" >/dev/null 2>&1 \
  || die "THE SIGNATURE DOES NOT MATCH the pinned public key: the release is not authentic (or was altered). Refusing." 2
MANIFEST_SHA="$("${SUM[@]}" "$DIR/MANIFEST.json" | awk '{print $1}')"
if [ -n "$EXPECT" ] && [ "$EXPECT" != "$MANIFEST_SHA" ]; then
  die "the manifest sha-256 ($MANIFEST_SHA) is not the expected one ($EXPECT)" 2
fi

# 2. the parts, from the (signed) manifest, never from a separate file
PARTS=()
CHECK="$TMP/parts.sums"
: > "$CHECK"
while read -r name sha; do
  [[ "$name" =~ ^[A-Za-z0-9._-]+\.age\.[0-9]{3}$ ]] || die "suspicious part name in the manifest: $name" 2
  [[ "$sha" =~ ^[0-9a-f]{64}$ ]] || die "invalid sha-256 in the manifest for $name" 2
  PARTS+=("$DIR/$name")
  printf '%s  %s\n' "$sha" "$DIR/$name" >> "$CHECK"
done < <(awk '/"parts": \[/ {p=1} p && /"name":/ {n=$0; sub(/.*"name": *"/, "", n); sub(/".*/, "", n)} p && /"sha256":/ {h=$0; sub(/.*"sha256": *"/, "", h); sub(/".*/, "", h); print n, h}' "$DIR/MANIFEST.json")
[ "${#PARTS[@]}" -gt 0 ] || die "the manifest lists no parts" 2
say "2/4 validating the fingerprints of the ${#PARTS[@]} part(s)…"
"${SUM[@]}" -c "$CHECK" >&2 || die "wrong fingerprints: the release is corrupted or was altered" 2

# 3. decrypt
if [ -z "$IDENTITY" ]; then
  if [ -t 0 ]; then
    read -r -p "3/4 path of the file with the age private key (AGE-SECRET-KEY-…): " IDENTITY
  else
    die "give the private key with -i FILE (or ARIADNE_AGE_IDENTITY)" 64
  fi
else
  say "3/4 private key: $IDENTITY"
fi
[ -r "$IDENTITY" ] || die "cannot read the private key at: $IDENTITY"
say "    decrypting…"
cat "${PARTS[@]}" | age -d -i "$IDENTITY" > "$TMP/content.tar.gz" || die "could not decrypt (wrong key?)" 3
WANT="$(sed -n 's/.*"content_sha256": *"\([0-9a-f]\{64\}\)".*/\1/p' "$DIR/MANIFEST.json" | head -n 1)"
GOT="$("${SUM[@]}" "$TMP/content.tar.gz" | awk '{print $1}')"
[ -n "$WANT" ] && [ "$WANT" = "$GOT" ] || die "the decrypted content does not match the manifest" 2
if tar -tzf "$TMP/content.tar.gz" | grep -Eq '(^/|(^|/)\.\.(/|$))'; then
  die "the archive has dangerous paths (absolute or with ..): refusing it" 2
fi
mkdir -p "$OUT"
tar -xzf "$TMP/content.tar.gz" -C "$OUT" --no-same-owner
ROOT="$OUT/ariadne-release"
[ -f "$ROOT/RELEASE.json" ] || die "the archive has no RELEASE.json"
say "    restored to $ROOT"

# 4. data for Postgres (only COPY of CSV; the schema is this script's)
if [ -n "$DATABASE" ]; then
  say "4/4 loading the data into database $DATABASE (schema ariadne_release)…"
  command -v psql >/dev/null || die "psql is missing for --database"
  psql -d "$DATABASE" -X -q -v ON_ERROR_STOP=1 >&2 <<'SCHEMA' || die "could not create the schema (does ariadne_release already exist?)" 4
@@SCHEMA_SQL@@
SCHEMA
  for table in info source wiki_page course; do
    [ -f "$ROOT/db/$table.csv" ] || die "db/$table.csv is missing" 4
    psql -d "$DATABASE" -X -q -v ON_ERROR_STOP=1 \
      -c "COPY ariadne_release.$table FROM STDIN WITH (FORMAT csv, NULL '\\N')" < "$ROOT/db/$table.csv" >&2 \
      || die "loading $table failed" 4
  done
else
  say "4/4 (no --database: the db/*.csv files are left unloaded)"
fi
say "Restore complete. Summary:"
cat "$ROOT/RELEASE.json"
